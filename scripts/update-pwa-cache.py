"""Refresh the atomic PWA shell manifest after changing any static app asset."""
from hashlib import sha256
from pathlib import Path
import json

ROOT = Path(__file__).resolve().parents[1]
paths = [ROOT / name for name in ('index.html', 'styles.css', 'manifest.webmanifest')]
paths += [path for path in ROOT.glob('*.js') if path.name not in ('sw.js', 'sw-assets.js')]
paths += list((ROOT / 'locales').glob('*.js'))
paths += list((ROOT / 'assets' / 'brands').glob('*.svg'))
paths += [path for path in (ROOT / 'assets' / 'app').glob('*') if path.is_file()]
assets = [{'url': path.relative_to(ROOT).as_posix(), 'revision': sha256(path.read_bytes()).hexdigest()}
          for path in sorted(paths)]
version = sha256((ROOT / 'sw.js').read_bytes() + json.dumps(assets, sort_keys=True, separators=(',', ':')).encode()).hexdigest()[:24]
content = ('/* Generated by scripts/update-pwa-cache.py; do not edit by hand. */\n'
           + f'self.SUMI_ASSET_VERSION = {json.dumps(version)};\n'
           + 'self.SUMI_ASSETS = ' + json.dumps(assets, ensure_ascii=False, indent=2) + ';\n')
(ROOT / 'sw-assets.js').write_text(content)
print(f'PWA manifest: {len(assets)} assets, version {version}')
