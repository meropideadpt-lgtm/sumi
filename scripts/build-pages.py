"""Package a verified static sumi release for GitHub Pages; never modify sources.

Run from any directory. The default destination is the repository's _site/;
--output can select a new directory elsewhere. Existing output is never deleted.
"""
from argparse import ArgumentParser
from hashlib import sha256
from pathlib import Path, PurePosixPath
import json
import os
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
BRAND_METADATA = (
    'assets/brands/LICENSE-dashboard-icons.txt',
    'assets/brands/LICENSE-lobe-icons.txt',
    'assets/brands/LICENSE-primer-octicons.txt',
    'assets/brands/DISCLAIMER-simple-icons.md',
    'assets/brands/LICENSE-simple-icons.txt',
    'assets/brands/manifest.json',
)
SDK_METADATA = ('assets/vendor/LICENSE-supabase.txt', 'assets/vendor/supabase.json')
MANIFEST_PATTERN = re.compile(
    r'/\* Generated by scripts/update-pwa-cache\.py; do not edit by hand\. \*/\s*'
    r'self\.SUMI_ASSET_VERSION\s*=\s*("[a-f0-9]{24}");\s*'
    r'self\.SUMI_ASSETS\s*=\s*(\[.*\]);\s*',
    re.DOTALL,
)


class BuildError(ValueError):
    """The source release or destination cannot be packaged safely."""


def no_symlinks(path):
    """Inspect lexical components before resolve() could hide a symlink."""
    path = Path(path)
    if '..' in path.parts:
        raise BuildError(f'Parent traversal is not allowed: {path}')
    absolute = Path(os.path.abspath(path))
    for component in reversed((absolute, *absolute.parents)):
        if component.is_symlink():
            raise BuildError(f'Symlinks are not allowed: {component}')
    return absolute


def read_source(root, name):
    path = no_symlinks(root / name)
    if not path.is_relative_to(root) or not path.is_file():
        raise BuildError(f'Missing regular source file: {name}')
    return path.read_bytes()


def expected_runtime_paths(root):
    paths = {'index.html', 'styles.css', 'manifest.webmanifest'}
    paths.update(path.name for path in root.glob('*.js')
                 if path.name not in ('sw.js', 'sw-assets.js'))
    paths.update(path.relative_to(root).as_posix()
                 for path in (root / 'locales').glob('*.js'))
    paths.update(path.relative_to(root).as_posix()
                 for path in (root / 'assets' / 'brands').glob('*.svg'))
    # App-icon formats are intentionally explicit; arbitrary backups/documents
    # in the asset directory must not become public deployment artifacts.
    paths.update(path.relative_to(root).as_posix()
                 for path in (root / 'assets' / 'app').glob('*')
                 if path.suffix in ('.png', '.svg', '.webp', '.ico') and path.is_file())
    return paths


def verified_files(root):
    manifest_bytes = read_source(root, 'sw-assets.js')
    try:
        match = MANIFEST_PATTERN.fullmatch(manifest_bytes.decode('utf-8'))
        if not match:
            raise BuildError('sw-assets.js is not a valid generated asset manifest.')
        version, assets = json.loads(match[1]), json.loads(match[2])
    except (UnicodeError, json.JSONDecodeError) as error:
        raise BuildError('sw-assets.js contains invalid UTF-8 or JSON.') from error
    if not isinstance(assets, list) or not assets:
        raise BuildError('The asset manifest must contain a nonempty asset list.')
    files = {}
    for asset in assets:
        if not isinstance(asset, dict) or set(asset) != {'url', 'revision'}:
            raise BuildError('Each manifest asset must have only url and revision.')
        url, revision = asset['url'], asset['revision']
        if (not isinstance(url, str) or not re.fullmatch(r'[A-Za-z0-9][A-Za-z0-9._/-]*', url)
                or PurePosixPath(url).as_posix() != url
                or any(part in ('.', '..') for part in PurePosixPath(url).parts)):
            raise BuildError(f'Unsafe asset path in manifest: {url!r}')
        if not isinstance(revision, str) or not re.fullmatch(r'[a-f0-9]{64}', revision):
            raise BuildError(f'Invalid SHA-256 revision: {url}')
        if url in files:
            raise BuildError(f'Duplicate asset path in manifest: {url}')
        source = read_source(root, url)
        if sha256(source).hexdigest() != revision:
            raise BuildError(f'Stale asset manifest: {url}; run scripts/update-pwa-cache.py and review the change.')
        files[url] = source
    expected = expected_runtime_paths(root)
    if set(files) != expected:
        missing, extra = sorted(expected - files.keys()), sorted(files.keys() - expected)
        raise BuildError(f'Runtime asset set differs from manifest (missing={missing}, extra={extra}).')
    worker = read_source(root, 'sw.js')
    canonical = json.dumps(assets, sort_keys=True, separators=(',', ':')).encode()
    if sha256(worker + canonical).hexdigest()[:24] != version:
        raise BuildError('Stale service-worker release version; run scripts/update-pwa-cache.py and review the change.')
    files.update({'sw.js':worker, 'sw-assets.js':manifest_bytes})
    for name in (*BRAND_METADATA, *SDK_METADATA):
        files[name] = read_source(root, name)
    files['.nojekyll'] = b''
    return files, version


def build_site(root=ROOT, output=None):
    root = no_symlinks(root)
    if not root.is_dir():
        raise BuildError(f'Repository directory does not exist: {root}')
    destination = no_symlinks(output if output is not None else root / '_site')
    if destination == root or destination in root.parents:
        raise BuildError('The output must not be the repository or one of its parent directories.')
    if destination.is_relative_to(root) and destination != root / '_site':
        raise BuildError('Inside the repository, only _site is allowed as the output directory.')
    if destination.exists():
        raise BuildError(f'Output already exists; choose a new directory: {destination}')
    # Validate and retain the exact bytes before creating anything. Sources that
    # change after this step cannot produce a mixed-version deployment artifact.
    files, version = verified_files(root)
    destination.mkdir(parents=True, exist_ok=False)
    for name, content in sorted(files.items()):
        target = destination / name
        target.parent.mkdir(parents=True, exist_ok=True)
        no_symlinks(target)
        with target.open('xb') as handle:
            handle.write(content)
    return destination, len(files), version


def main(argv=None):
    parser = ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, help='New output directory (default: repository/_site)')
    args = parser.parse_args(argv)
    try:
        destination, count, version = build_site(output=args.output)
    except (BuildError, OSError) as error:
        print(f'Pages build failed: {error}', file=sys.stderr)
        return 1
    print(f'Pages artifact: {count} files, release {version}, output {destination}')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
