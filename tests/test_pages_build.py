"""Static deployment packaging checks; no browser, network or publishing actions."""
from hashlib import sha256
import importlib.util
import json
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile
import unittest

ROOT = Path(__file__).resolve().parents[1]
SPEC = importlib.util.spec_from_file_location('sumi_pages_build', ROOT / 'scripts/build-pages.py')
BUILD = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(BUILD)


class PagesBuildTests(unittest.TestCase):
    def setUp(self):
        self.temporary = tempfile.TemporaryDirectory(prefix='sumi-pages-')
        self.addCleanup(self.temporary.cleanup)
        self.base = Path(self.temporary.name)
        self.root = self.base / 'source'
        self.root.mkdir()
        self.output = self.base / 'public'
        self.files, self.version = BUILD.verified_files(ROOT)
        for name, content in self.files.items():
            if name == '.nojekyll':
                continue
            target = self.root / name
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(content)

    def manifest(self):
        source = (self.root / 'sw-assets.js').read_text()
        match = BUILD.MANIFEST_PATTERN.fullmatch(source)
        return json.loads(match[2])

    def write_manifest(self, assets, version=None):
        version = version or sha256((self.root / 'sw.js').read_bytes()
            + json.dumps(assets, sort_keys=True, separators=(',', ':')).encode()).hexdigest()[:24]
        (self.root / 'sw-assets.js').write_text(
            '/* Generated by scripts/update-pwa-cache.py; do not edit by hand. */\n'
            + f'self.SUMI_ASSET_VERSION = {json.dumps(version)};\n'
            + 'self.SUMI_ASSETS = ' + json.dumps(assets, indent=2) + ';\n')

    def test_build_contains_exact_verified_runtime_worker_licenses_and_nojekyll(self):
        for name in ('.git/config', 'tests/private.json', 'README.md', 'sumi-backup.json', 'data/user.json'):
            path = self.root / name
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text('must stay private')
        destination, count, version = BUILD.build_site(self.root, self.output)
        self.assertEqual((destination, count, version), (self.output, len(self.files), self.version))
        actual = {path.relative_to(destination).as_posix():path.read_bytes()
                  for path in destination.rglob('*') if path.is_file()}
        self.assertEqual(actual, self.files)
        self.assertEqual(actual['.nojekyll'], b'')
        for name in BUILD.BRAND_METADATA:
            self.assertEqual(actual[name], (self.root / name).read_bytes())
        for asset in self.manifest():
            self.assertEqual(sha256(actual[asset['url']]).hexdigest(), asset['revision'])

    def test_default_output_is_repository_site_and_sources_are_unchanged(self):
        before = {name:(self.root / name).read_bytes() for name in self.files if name != '.nojekyll'}
        destination, _, _ = BUILD.build_site(self.root)
        self.assertEqual(destination, self.root / '_site')
        self.assertEqual(before, {name:(self.root / name).read_bytes() for name in before})

    def test_stale_asset_fails_without_output_or_silent_manifest_regeneration(self):
        original = (self.root / 'sw-assets.js').read_bytes()
        (self.root / 'app.js').write_bytes(b'new source not yet reviewed')
        with self.assertRaisesRegex(BUILD.BuildError, 'Stale asset manifest: app.js'):
            BUILD.build_site(self.root, self.output)
        self.assertFalse(self.output.exists())
        self.assertEqual((self.root / 'sw-assets.js').read_bytes(), original)

    def test_worker_change_requires_a_matching_release_version(self):
        with (self.root / 'sw.js').open('ab') as handle:
            handle.write(b'\n// new worker\n')
        with self.assertRaisesRegex(BUILD.BuildError, 'Stale service-worker release version'):
            BUILD.build_site(self.root, self.output)
        self.assertFalse(self.output.exists())

    def test_missing_runtime_or_license_file_aborts_before_output_is_created(self):
        for name in ('index.html', BUILD.BRAND_METADATA[0]):
            with self.subTest(name=name):
                path = self.root / name
                original = path.read_bytes()
                path.unlink()
                with self.assertRaisesRegex(BUILD.BuildError, 'Missing regular source file'):
                    BUILD.build_site(self.root, self.output)
                self.assertFalse(self.output.exists())
                path.write_bytes(original)

    def test_unlisted_runtime_script_requires_manifest_update(self):
        (self.root / 'new-feature.js').write_text('/* newly added runtime module */')
        with self.assertRaisesRegex(BUILD.BuildError, 'Runtime asset set differs'):
            BUILD.build_site(self.root, self.output)
        self.assertFalse(self.output.exists())

    def test_manifest_cannot_publish_user_data_or_unlisted_directories(self):
        for name in ('sumi-backup.json', 'tests/fixture.json', '.git/config'):
            with self.subTest(name=name):
                path = self.root / name
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_bytes(b'private')
                assets = self.manifest()
                assets.append({'url':name, 'revision':sha256(b'private').hexdigest()})
                original = (self.root / 'sw-assets.js').read_bytes()
                self.write_manifest(assets)
                with self.assertRaises(BUILD.BuildError):
                    BUILD.build_site(self.root, self.output)
                self.assertFalse(self.output.exists())
                (self.root / 'sw-assets.js').write_bytes(original)

    def test_malformed_manifest_duplicate_path_and_path_traversal_are_rejected(self):
        original = (self.root / 'sw-assets.js').read_bytes()
        valid = self.manifest()
        variants = [valid + [valid[0]],
                    [{'url':'../outside.js', 'revision':'0'*64}],
                    [{'url':'/app.js', 'revision':'0'*64}],
                    [{'url':'https://example.test/app.js', 'revision':'0'*64}],
                    [{'url':'locales//app.js', 'revision':'0'*64}],
                    [{'url':'app.js', 'revision':'not a sha256'}],
                    [{'url':'app.js', 'revision':'0'*64, 'unexpected':True}]]
        for assets in variants:
            with self.subTest(assets=assets[-1]):
                self.write_manifest(assets)
                with self.assertRaises(BUILD.BuildError):
                    BUILD.build_site(self.root, self.output)
                self.assertFalse(self.output.exists())
        (self.root / 'sw-assets.js').write_bytes(original + b'\nthrow new Error("not a manifest");')
        with self.assertRaisesRegex(BUILD.BuildError, 'valid generated asset manifest'):
            BUILD.build_site(self.root, self.output)
        self.assertFalse(self.output.exists())

    def test_source_file_and_source_directory_symlinks_are_rejected(self):
        for name in ('app.js', BUILD.BRAND_METADATA[0]):
            with self.subTest(name=name):
                source = self.root / name
                content = source.read_bytes()
                target = self.base / 'external-source'
                target.write_bytes(content)
                source.unlink()
                source.symlink_to(target)
                with self.assertRaisesRegex(BUILD.BuildError, 'Symlinks are not allowed'):
                    BUILD.build_site(self.root, self.output)
                self.assertFalse(self.output.exists())
                self.assertEqual(target.read_bytes(), content)
                source.unlink()
                source.write_bytes(content)
        outside = self.base / 'external-locales'
        (self.root / 'locales').rename(outside)
        (self.root / 'locales').symlink_to(outside, target_is_directory=True)
        with self.assertRaisesRegex(BUILD.BuildError, 'Symlinks are not allowed'):
            BUILD.build_site(self.root, self.output)
        self.assertFalse(self.output.exists())

    def test_output_never_replaces_existing_files_or_directories(self):
        self.output.mkdir()
        marker = self.output / 'keep.txt'
        marker.write_text('keep existing output')
        with self.assertRaisesRegex(BUILD.BuildError, 'Output already exists'):
            BUILD.build_site(self.root, self.output)
        self.assertEqual(marker.read_text(), 'keep existing output')
        file = self.base / 'existing-file'
        file.write_text('keep existing file')
        with self.assertRaisesRegex(BUILD.BuildError, 'Output already exists'):
            BUILD.build_site(self.root, file)
        self.assertEqual(file.read_text(), 'keep existing file')

    def test_repository_ancestors_and_other_source_subdirectories_are_not_destinations(self):
        before = (self.root / 'app.js').read_bytes()
        for path in (self.root, self.base, self.root / 'assets', self.root / 'new-output'):
            with self.subTest(path=path):
                with self.assertRaises(BUILD.BuildError):
                    BUILD.build_site(self.root, path)
        self.assertEqual((self.root / 'app.js').read_bytes(), before)
        self.assertFalse((self.root / 'new-output').exists())

    def test_output_rejects_symlink_parent_leaf_dangling_link_and_parent_traversal(self):
        external = self.base / 'external'
        external.mkdir()
        link = self.base / 'linked'
        link.symlink_to(external, target_is_directory=True)
        dangling = self.base / 'dangling'
        dangling.symlink_to(self.base / 'not-created', target_is_directory=True)
        for path in (link, link / 'site', dangling, external / '..' / 'public'):
            with self.subTest(path=path):
                with self.assertRaises(BUILD.BuildError):
                    BUILD.build_site(self.root, path)
        self.assertEqual(list(external.iterdir()), [])
        self.assertFalse((self.base / 'not-created').exists())

    def test_cli_packages_current_repository_into_an_explicit_new_destination(self):
        result = subprocess.run([sys.executable, str(ROOT / 'scripts/build-pages.py'), '--output', str(self.output)],
                                cwd=self.base, capture_output=True, text=True, check=False)
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertIn(f'{len(self.files)} files', result.stdout)
        self.assertIn(self.version, result.stdout)
        self.assertEqual((self.output / 'index.html').read_bytes(), (ROOT / 'index.html').read_bytes())
        repeat = subprocess.run([sys.executable, str(ROOT / 'scripts/build-pages.py'), '--output', str(self.output)],
                                cwd=self.base, capture_output=True, text=True, check=False)
        self.assertEqual(repeat.returncode, 1)
        self.assertIn('Output already exists', repeat.stderr)
        self.assertEqual((self.output / 'index.html').read_bytes(), (ROOT / 'index.html').read_bytes())


if __name__ == '__main__':
    unittest.main()
